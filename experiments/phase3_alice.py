"""Phase 3 Educational Demonstration: Alice (Sender) in BB84.

This script demonstrates Alice's complete workflow in BB84:
1. Generating a random classical bit sequence.
2. Generating a random measurement basis sequence ('Z' or 'X').
3. Encoding bit/basis pairs into corresponding single-qubit quantum states.
4. Preserving Alice's private classical records.
5. Displaying the resulting signal states and quantum circuits.

Usage:
    .venv/Scripts/python experiments/phase3_alice.py
    .venv/Scripts/python experiments/phase3_alice.py --signals 12 --seed 42
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Ensure UTF-8 output on platforms where default stdout is cp1252 (e.g. Windows)
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Add project root to sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.alice import Alice


def run_alice_demonstration(num_signals: int = 10, seed: int = 42) -> None:
    """Execute the Alice state preparation demonstration."""
    print("=" * 76)
    print("           BB84 QUANTUM KEY DISTRIBUTION: PHASE 3 DEMONSTRATION")
    print("                         Alice (Sender) Component")
    print("=" * 76)
    print(f"Configuration: number_of_qubits={num_signals}, seed={seed}\n")

    # Step 1: Initialize Alice
    alice = Alice(number_of_qubits=num_signals, seed=seed)

    # Step 2: Generate bits
    bits = alice.generate_bits()
    print("1. Alice's Raw Classical Bits (Private):")
    print(f"   {' '.join(str(b) for b in bits)}\n")

    # Step 3: Generate bases
    bases = alice.generate_bases()
    print("2. Alice's Encoding Bases (Private):")
    print(f"   {' '.join(bases)}\n")

    # Step 4: Encode states into quantum signals
    signals = alice.encode()
    symbols = alice.get_state_symbols()
    print("3. Prepared Quantum State Sequence (Dirac Notation):")
    print(f"   {' '.join(symbols)}\n")

    # Step 5: Tabular breakdown
    print("=" * 76)
    print(f"{'Index':<7} | {'Bit':<5} | {'Basis':<7} | {'State':<7} | {'Encoding Circuit Gates':<20}")
    print("-" * 76)
    for sig in signals:
        ops = [op.operation.name.upper() for op in sig.circuit.data]
        ops_str = " -> ".join(ops) if ops else "(ground |0>)"
        print(f"{sig.index:<7} | {sig.bit:<5} | {sig.basis:<7} | {sig.state_symbol:<7} | {ops_str:<20}")
    print("=" * 76)

    # Step 6: Display sample circuits for each unique state
    print("\nSample Quantum Circuits Generated by Alice:")
    seen_states = set()
    for sig in signals:
        if sig.state_symbol not in seen_states:
            seen_states.add(sig.state_symbol)
            print(f"\nState {sig.state_symbol} (bit={sig.bit}, basis={sig.basis}):")
            circuit_str = str(sig.circuit.draw(output="text"))
            for line in circuit_str.splitlines():
                print(f"  {line}")
        if len(seen_states) == 4:
            break

    # Step 7: Quantum Channel Isolation Demonstration
    quantum_circuits = alice.get_quantum_signals()
    print("\n" + "=" * 76)
    print("4. Quantum Channel Transmission Isolation:")
    print(f"   Alice transmits {len(quantum_circuits)} physical quantum circuits across the channel.")
    print("   Bob/Eve interface receives ONLY the quantum carrier states.")
    print("   Alice's private bit and basis records remain shielded.")
    print("=" * 76 + "\n")


def parse_args() -> argparse.Namespace:
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description="BB84 Phase 3 Alice Demonstration")
    parser.add_argument(
        "--signals",
        type=int,
        default=10,
        help="Number of quantum signals to generate (default: 10)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducible generation (default: 42)",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    run_alice_demonstration(num_signals=args.signals, seed=args.seed)
